// One-off: extracts the 4 body figures from the owner's 2D prototype (MuscleMap art, MIT) into
// src/ui/body/figures/*.ts and writes src/ui/body/regions.ts. Not run in CI. See docs/BODY_PICKER.md P16.1.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const PROTO = 'reference/prototypes/muscle_lab_2d.html';
const CSV = 'contract/dataset/detailed_muscles/html_unit_to_detailed.csv';
const OUT = 'src/ui/body/figures';

const line = readFileSync(PROTO, 'utf8').split('\n')[147].replace(/data:image\/[a-z]+;base64,[A-Za-z0-9+/=]+/g, 'IMG');
const F = (0, eval)('(' + line.slice(line.indexOf('const F=') + 8).trim().replace(/;$/, '') + ')');
const csv = new Map(
  readFileSync(CSV, 'utf8').split(/\r?\n/).slice(1).filter(Boolean).map((l) => {
    const c = l.split(',');
    return [c[0], c[2]];
  }),
);

function box(d) {
  const n = d.match(/-?\d*\.?\d+/g).map(Number);
  const xs = [], ys = [];
  for (let i = 0; i + 1 < n.length; i += 2) { xs.push(n[i]); ys.push(n[i + 1]); }
  const x = Math.min(...xs), y = Math.min(...ys);
  return [Math.round(x), Math.round(y), Math.round(Math.max(...xs) - x), Math.round(Math.max(...ys) - y)];
}

mkdirSync(OUT, { recursive: true });
const tiers = {}; // muscle -> { views:Set, allApprox:boolean }
let total = 0;
for (const key of Object.keys(F)) {
  const [sex, view] = key.split('_');
  const name = sex + view[0].toUpperCase() + view.slice(1);
  const units = F[key].units.map((u) => {
    const muscle = csv.get(u.id);
    if (!muscle) throw new Error('unit not in CSV: ' + u.id);
    const t = (tiers[muscle] ??= { views: new Set(), allApprox: true });
    t.views.add(view);
    if (u.tier !== 'approximate') t.allApprox = false;
    total += 1;
    const o = { id: u.id, region: u.muscle, muscle, tier: u.tier === 'approximate' ? 'approximate' : 'clear', box: box(u.d), d: u.d };
    if (u.clip) o.clip = u.clip;
    return o;
  });
  const body =
    `// Generated by scripts/extract-body-figures.mjs from the MuscleMap art (MIT). Do not edit by hand.\n` +
    `import type { Figure } from './types';\n\n` +
    `export const fig: Figure = ${JSON.stringify({ outline: F[key].outline, units })};\n`;
  writeFileSync(`${OUT}/${name}.ts`, body);
}
const rows = Object.keys(tiers).sort().map((m) =>
  `  ${m}: { tier: '${tiers[m].allApprox ? 'approx' : 'clear'}', views: [${[...tiers[m].views].sort().map((v) => `'${v}'`).join(', ')}] },`);
writeFileSync('src/ui/body/regions.ts',
  `// Generated by scripts/extract-body-figures.mjs. Which detailed muscles have a drawn region, and on which view.\n` +
  `export const REGIONS: Record<string, { tier: 'clear' | 'approx'; views: Array<'front' | 'back'> }> = {\n${rows.join('\n')}\n};\n`);
console.log('units', total);
